"""Generate NSIS's runtime files and their installed inventory from one list.

    python scripts/installer_payload.py RUNTIME OUT.nsh

The inventory lets upgrades remove the previous payload without wildcards or
recursive deletion. Unrelated files and non-empty folders stay in place.
"""

from __future__ import annotations

import sys
from pathlib import Path


def nsis(text: str) -> str:
    """A literal NSIS string, including Windows paths."""
    return text.replace("$", "$$").replace('"', '$\\"')


def payload(runtime: Path) -> str:
    """The install macro, recording exactly the files it extracts."""
    runtime = runtime.resolve(strict=True)
    entries = sorted(runtime.rglob("*"))
    if not entries:
        raise ValueError("the runtime folder is empty")
    lines = ["; Generated by scripts/installer_payload.py; do not edit.", "!macro LUMEN_RUNTIME_FILES"]
    folders: set[str] = set()
    for path in entries:
        if path.is_symlink() or path.is_junction():
            raise ValueError(f"the runtime contains a link: {path}")
        if not path.is_file():
            continue
        relative = path.relative_to(runtime)
        name = str(relative).replace("/", "\\")
        if len(name) >= 900 or any(c in name for c in '\r\n:*?"'):
            raise ValueError(f"the runtime path cannot be recorded by NSIS: {relative}")
        parent = str(relative.parent).replace("/", "\\")
        target = "$INSTDIR" + ("\\" + nsis(parent) if parent != "." else "")
        lines.extend(
            [
                f'    SetOutPath "{target}"',
                f'    File "{nsis(str(path))}"',
                f'    FileWriteUTF16LE $R9 "F{nsis(name)}$\\r$\\n"',
                "    !insertmacro LUMEN_PAYLOAD_CHECK",
            ]
        )
        folders.update(str(p).replace("/", "\\") for p in relative.parents if str(p) != ".")
    for folder in sorted(folders, key=lambda p: (-p.count("\\"), p)):
        lines.append(f'    FileWriteUTF16LE $R9 "D{nsis(folder)}$\\r$\\n"')
    lines.append("    !insertmacro LUMEN_PAYLOAD_CHECK")
    lines.extend(['    SetOutPath "$INSTDIR"', "!macroend", ""])
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("usage: python scripts/installer_payload.py RUNTIME OUT.nsh")
    Path(sys.argv[2]).write_text(payload(Path(sys.argv[1])), encoding="utf-8")


if __name__ == "__main__":
    main()
