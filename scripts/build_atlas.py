"""Regenerate the offline dot atlas: python scripts/build_atlas.py.

Uses the committed GeoNames catalogue and the approved artboard's projection.
Only the quantised land cells ship; no city catalogue is duplicated in the UI.
"""

import gzip
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COLS, ROWS = 90, 36
LON0, LAT0, LAT1 = -168, 80, -64


def main() -> None:
    land = [[0] * COLS for _ in range(ROWS)]
    with gzip.open(ROOT / "internal/places/cities.tsv.gz", "rt", encoding="utf-8") as source:
        for line in source:
            fields = line.split("\t")
            lat, lon = float(fields[2]), float(fields[3])
            col = int(((lon - LON0) % 360) / 360 * COLS)
            row = int((LAT0 - lat) / (LAT0 - LAT1) * ROWS)
            if 0 <= row < ROWS:
                land[row][col] = 1
    # Close small gaps twice so city cells read as continuous land masses.
    for _ in range(2):
        next_land = [row[:] for row in land]
        for row in range(ROWS):
            for col in range(COLS):
                neighbours = sum(
                    land[y][x]
                    for y in range(max(0, row - 1), min(ROWS, row + 2))
                    for x in range(max(0, col - 1), min(COLS, col + 2))
                    if (y, x) != (row, col)
                )
                if neighbours >= 5:
                    next_land[row][col] = 1
        land = next_land
    # Hexadecimal row bitsets keep the checked-in module below two kilobytes.
    rows = [format(int("".join(map(str, row)), 2), "023x") for row in land]
    output = (
        "// Generated by python scripts/build_atlas.py from the bundled GeoNames catalogue.\n"
        "// The projection matches Places.dc.html; regenerate rather than editing these cells.\n"
        f"export const ATLAS_COLUMNS = {COLS}\nexport const ATLAS_ROWS = {ROWS}\n"
        f"export const ATLAS_WEST = {LON0}\nexport const ATLAS_NORTH = {LAT0}\n"
        f"export const ATLAS_SOUTH = {LAT1}\n"
        "export const atlasCells = [\n" + "".join(f"  '{row}',\n" for row in rows) + "]\n"
    )
    (ROOT / "frontend/src/places/atlasData.ts").write_bytes(output.encode("utf-8"))


if __name__ == "__main__":
    main()
